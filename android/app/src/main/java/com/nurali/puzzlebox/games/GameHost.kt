package com.nurali.puzzlebox.games

import androidx.compose.runtime.Composable
import com.nurali.puzzlebox.core.GameId

/** Maps a game id to its playable screen. The one place to register a new game's UI. */
@Composable
fun GameHost(id: GameId, onExit: () -> Unit) {
    when (id) {
        GameId.Game2048 -> Game2048Screen(onExit)
        GameId.Snake -> SnakeScreen(onExit)
        GameId.Minesweeper -> MinesweeperScreen(onExit)
        GameId.QuickMath -> QuickMathScreen(onExit)
        GameId.Simon -> BrainScreen(BrainMode.Simon, onExit)
        GameId.ReactionTap -> BrainScreen(BrainMode.Reaction, onExit)
        GameId.LightsOut -> PuzzleScreen(PuzzleMode.LightsOut, onExit)
        GameId.Nonogram -> PuzzleScreen(PuzzleMode.Nonogram, onExit)
        GameId.NumberConnect -> PuzzleScreen(PuzzleMode.NumberConnect, onExit)
        GameId.OneLine -> PuzzleScreen(PuzzleMode.OneLine, onExit)
        GameId.Unblock -> PuzzleScreen(PuzzleMode.Unblock, onExit)
        GameId.FifteenPuzzle -> PuzzleScreen(PuzzleMode.FifteenPuzzle, onExit)
        GameId.PipeConnect -> PuzzleScreen(PuzzleMode.PipeConnect, onExit)
        GameId.Dots -> PuzzleScreen(PuzzleMode.Dots, onExit)
        GameId.FloodFill -> PuzzleScreen(PuzzleMode.FloodFill, onExit)
        GameId.Laser -> PuzzleScreen(PuzzleMode.Laser, onExit)
        GameId.ColorLines -> PuzzleScreen(PuzzleMode.ColorLines, onExit)
        GameId.ArrowMaze -> RocketMazeScreen(onExit)
        GameId.ArrowEscape -> ArrowEscapeScreen(onExit)
        GameId.Bounce -> BounceScreen(onExit)
        GameId.BasketShot -> ToyScreen(ToyMode.BasketShot, onExit)
        GameId.BottleFlip -> ToyScreen(ToyMode.BottleFlip, onExit)
        GameId.MiniGolf -> ToyScreen(ToyMode.MiniGolf, onExit)
        GameId.Plinko -> ToyScreen(ToyMode.Plinko, onExit)
        GameId.RopeCut -> ToyScreen(ToyMode.RopeCut, onExit)
        GameId.DrawBridge -> ToyScreen(ToyMode.DrawBridge, onExit)
        GameId.Checkmate -> CheckmateScreen(onExit)
        GameId.BlockBlast -> BlockBlastScreen(onExit)
        GameId.Sudoku -> SudokuScreen(onExit)
        GameId.WaterSort -> WaterSortScreen(onExit)
        GameId.Togyzkumalak -> TogyzScreen(onExit)
        GameId.Altybakan -> AltybakanScreen(onExit)
        GameId.Kokpar -> KokparScreen(onExit)
        GameId.Baige -> BaigeScreen(onExit)
        GameId.Asyk -> AsykScreen(onExit)
        GameId.Crossword -> CrosswordScreen(onExit)
        GameId.Solitaire -> SolitaireScreen(onExit)
        GameId.SpiderSolitaire -> SpiderScreen(onExit)
        GameId.Freecell -> FreeCellScreen(onExit)
        GameId.FindColor -> AttentionScreen(AttentionMode.FindColor, onExit)
        GameId.FindPair -> AttentionScreen(AttentionMode.FindPair, onExit)
        GameId.RotatePuzzle -> VisualScreen(VisualMode.RotatePuzzle, onExit)
        GameId.Matchstick -> VisualScreen(VisualMode.Matchstick, onExit)
        GameId.Slope -> MotionScreen(MotionMode.Slope, onExit)
        GameId.CirclePong -> MotionScreen(MotionMode.CirclePong, onExit)
        GameId.SpaceDodge -> MotionScreen(MotionMode.SpaceDodge, onExit)
        GameId.EndlessClimb -> MotionScreen(MotionMode.EndlessClimb, onExit)
        GameId.MergeFruit -> MergeFruitScreen(onExit)
        GameId.Stack -> ArcadeScreen(ArcadeMode.Stack, onExit)
        GameId.KnifeSpin -> ArcadeScreen(ArcadeMode.KnifeSpin, onExit)
        GameId.HelixDrop -> ArcadeScreen(ArcadeMode.HelixDrop, onExit)
        GameId.FlappyFlight -> ArcadeScreen(ArcadeMode.FlappyFlight, onExit)
        GameId.RoadHop -> ArcadeScreen(ArcadeMode.RoadHop, onExit)
        GameId.RedGreen -> ActionScreen(ActionMode.RedGreen, onExit)
        GameId.PerfectTiming -> ActionScreen(ActionMode.PerfectTiming, onExit)
        GameId.BubblePop -> ActionScreen(ActionMode.BubblePop, onExit)
        GameId.WhackMole -> ActionScreen(ActionMode.WhackMole, onExit)
        GameId.ChainReaction -> ActionScreen(ActionMode.ChainReaction, onExit)
    }
}
